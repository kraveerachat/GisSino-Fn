// Run after changing any shell source. Generates an explicit immutable allowlist.
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
async function walk(dir) {
  const entries = await readdir(path.join(root, dir), { withFileTypes: true });
  return (await Promise.all(entries.map(entry => entry.isDirectory() ? walk(`${dir}/${entry.name}`) : `${dir}/${entry.name}`))).flat();
}
const paths = ['index.html','manifest.webmanifest',...await walk('src'),...await walk('icons'),...await walk('assets')]
  .filter(file => /\.(?:js|css|png|webp|svg|ttf|html|webmanifest)$/.test(file) && !file.startsWith('assets/pwa/')).sort();
const hash = createHash('sha256');
for (const file of paths) { hash.update(file); const bytes=await readFile(path.join(root,file)); hash.update(/\.(?:js|css|svg|html|webmanifest)$/.test(file)?bytes.toString('utf8').replace(/\r\n/g,'\n'):bytes); }
hash.update((await readFile(path.join(root,'sw.js'),'utf8')).replace(/\r\n/g,'\n'));
const shell = { version: hash.digest('hex').slice(0,16), paths: paths.map(file => '/' + file) };
await mkdir(path.join(root,'assets/pwa'), { recursive:true });
const generated = '// Generated by scripts/build-pwa.mjs; do not edit.\nself.GISSINO_SHELL = ' + JSON.stringify(shell,null,2) + ';\n';
if (process.argv.includes('--check')) { if ((await readFile(path.join(root,'assets/pwa/shell.js'),'utf8')).replace(/\r\n/g,'\n') !== generated) throw new Error('PWA shell is stale: run npm run pwa:build'); }
else await writeFile(path.join(root,'assets/pwa/shell.js'), generated);
console.log(`Generated shell ${shell.version}: ${paths.length} allowlisted assets`);
